export function translateKey(lang: AppLanguage, key: string): string {
  return TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? key;
}

export function localizeCategoryName(lang: AppLanguage, rawName: string): string {
  if (lang === 'ar' && CATEGORY_NAME_AR[rawName]) {
    return CATEGORY_NAME_AR[rawName];
  }
  return rawName;
}

export function localizeHomeSectionTitle(
  lang: AppLanguage,
  sectionId: string,
  fallbackTitle: string
): string {
  if (lang === 'ar' && HOME_SECTION_TITLE_AR[sectionId]) {
    return HOME_SECTION_TITLE_AR[sectionId];
  }
  return fallbackTitle;
}
